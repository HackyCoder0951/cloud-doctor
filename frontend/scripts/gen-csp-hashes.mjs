// Computes SHA-256 hashes of every inline <script> in the static export and writes them as an nginx
// include (infra/nginx/csp-script-hashes.conf), so script-src can be 'self' + hashes with NO 'unsafe-inline'.
//   node scripts/gen-csp-hashes.mjs          write the include (runs as `postbuild`)
//   node scripts/gen-csp-hashes.mjs --check  exit 1 if the include does not match out/
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(root, 'out');
export const INCLUDE = join(root, '..', 'infra', 'nginx', 'csp-script-hashes.conf');

function htmlFiles(dir, acc = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) htmlFiles(p, acc);
    else if (n.endsWith('.html')) acc.push(p);
  }
  return acc;
}

/** Inline scripts: <script> elements without a src attribute. */
export function inlineScripts(html) {
  const out = [];
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) if (!/\bsrc\s*=/.test(m[1])) out.push(m[2]);
  return out;
}

export function collectHashes(outDir = OUT) {
  const set = new Set();
  for (const f of htmlFiles(outDir)) for (const s of inlineScripts(readFileSync(f, 'utf8'))) set.add(`'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`);
  return [...set].sort();
}

export function render(hashes) {
  return [
    '# GENERATED by frontend/scripts/gen-csp-hashes.mjs from the static export (frontend/out). Do not edit.',
    '# Allow-list of the SHA-256 hashes of Next.js\'s inline bootstrap/flight-data scripts (see docs/dev/frontend/STATUS.md, F1).',
    '# Regenerate after every `npm run build` (done by the postbuild script); the build id is fixed so rebuilding the same source is reproducible.',
    `set $cd_script_hashes "${hashes.join(' ')}";`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(OUT)) { console.error('frontend/out does not exist: run `npm run build` first'); process.exit(1); }
  const text = render(collectHashes());
  if (process.argv.includes('--check')) {
    if (!existsSync(INCLUDE) || readFileSync(INCLUDE, 'utf8') !== text) { console.error('infra/nginx/csp-script-hashes.conf is stale: run `npm run build` (or `node scripts/gen-csp-hashes.mjs`).'); process.exit(1); }
    console.log('ok: csp-script-hashes.conf matches the static export');
  } else {
    writeFileSync(INCLUDE, text);
    console.log(`wrote ${INCLUDE} (${text.split("'sha256-").length - 1} hashes)`);
  }
}
