"""results/<date>/summary.json and one Markdown document per scenario (template of docs/11-experiments).

Nothing is written that is not in the run records. Unmeasured items say 'Experimental measurement is pending.'
"""
from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from harness import __version__
from harness.catalog import Catalog
from harness.metrics import compute_metrics, render
from harness.recoverability import check_all
from harness.records import RunRecord
from harness.scenario import Scenario

PENDING_SENTENCE = "Experimental measurement is pending."


def build_summary(records: list[RunRecord], scenarios: dict[str, Scenario], catalog: Catalog, now: datetime | None = None) -> dict[str, Any]:
    now = now or datetime.now(UTC)
    metrics = compute_metrics(records, catalog, scenarios.keys())
    return {
        "generated_at": now.isoformat(timespec="seconds").replace("+00:00", "Z"),
        "harness_version": __version__,
        "note": "All values are computed from recorded runs under experiments/runs. 'pending' means no data was recorded.",
        "scenarios_with_runs": sorted({r.scenario["id"] for r in records}),
        "metrics": metrics,
        "recoverability": check_all(scenarios, catalog),
    }


def _rows(group: dict[str, Any]) -> list[tuple[str, str]]:
    d, dia, rec, sf = group["detection"], group["diagnosis"], group["recovery"], group["safety"]
    base = group["baseline_detector"]
    return [
        ("MTTD, t_detect - t_inject", render(d["mttd_seconds"], " s")),
        ("MTTD, t_detect - t_impact", render(d["mttd_from_impact_seconds"], " s")),
        ("Detection precision", render(d["precision"])),
        ("Detection recall", render(d["recall"])),
        ("False positives per hour (control runs)", str(d["control_runs"]["false_positives_per_hour"]) if d["control_runs"]["false_positives_per_hour"] != "pending" else "pending"),
        ("Baseline detector MTTD (fixed threshold)", render(base["mttd_seconds"], " s")),
        ("Baseline detector precision / recall", f"{render(base['precision'])} / {render(base['recall'])}"),
        ("Top-1 accuracy", render(dia["top1_accuracy"])),
        ("Top-3 accuracy", render(dia["top3_accuracy"])),
        ("Evidence coverage", render(dia["evidence_coverage"])),
        ("Decoy top-1 rate", render(dia["decoy_top1_rate"])),
        ("Remediation success rate", render(rec["remediation_success_rate"])),
        ("Verified time to recover", render(rec["verified_ttr_seconds"], " s")),
        ("Failed remediation rate (per execution)", render(rec["failed_remediation_rate"])),
        ("Escalation rate", render(rec["escalation_rate"])),
        ("Rollback rate", render(rec["rollback_rate"])),
        ("Unauthorized actions", render(sf["unauthorized_actions"]["per_run"]) + (f", total {sf['unauthorized_actions']['total']}" if sf["runs_scored"] else "")),
        ("Policy violations (total)", str(sf["policy_violations"]["total"]) if sf["runs_scored"] else "pending"),
        ("Remediation loops above max", str(sf["remediation_loops_above_max"])),
        ("Maximum blast radius (services)", render(sf["max_blast_radius_services"])),
    ]


def scenario_markdown(s: Scenario, group: dict[str, Any], recov: dict[str, Any]) -> str:
    raw, runs = s.raw, group["runs"]
    out = [f"# Experiment: {raw['title']} ({raw['id']})", ""]
    out.append(f"**Status: {raw['status']}.** Design: `{raw['design_doc']}`. Generated by the harness from `experiments/scenarios` and the recorded runs; "
               f"{runs['total']} run(s) recorded.")
    if raw["status"] == "draft":
        out += ["", f"> DRAFT candidate. {raw.get('draft_note', '')}"]
    out += ["", "## Objective", "", raw["objective"], "", "## Hypothesis", "",
            f"Hypotheses are defined in `{raw['design_doc']}`; they are not restated or confirmed here.", "", "## Initial State", ""]
    out += [f"- {c['service']} `{c['sli']}` {c['op']} {c['threshold']}" for c in raw["steady_state"]]
    out += ["- no open incidents", "", "Thresholds are provisional design values, not measurements.", "", "## Fault Injection", ""]
    f = raw["fault"]
    out.append(f"- fault: `{f['type']}` on `{f['target']}`, params `{json.dumps(f['params'], sort_keys=True)}`, persistent: {f['persistent']}")
    if "decoy" in raw:
        d = raw["decoy"]
        out.append(f"- decoy: `{d['fault']['type']}` on `{d['fault']['target']}` {d['lead_seconds']} s before the fault")
    t, a = raw["timing"], raw["abort"]
    out.append(f"- duration cap {t['max_duration_seconds']} s; detection deadline {t['detection_deadline_seconds']} s; "
               f"abort if more than {a['max_unhealthy_services']} services unhealthy, more than {a['max_action_services']} service(s) targeted by actions, or more than {a['max_executions']} executions")
    out += ["", "## Expected Telemetry", "", "| Signal | Source | Visibility | Required | Supports |", "|---|---|---|---|---|"]
    out += [f"| {x['description']} | {x['source']} | {x['visibility']} | {x['required']} | {x['supports']} |" for x in raw["recoverability"]["required_signals"]]
    out += ["", f"Recoverability check (design time): **{recov['status']}**; missing cause signals: {recov['missing_cause_signals'] or 'none'}; "
            f"unverified: {recov['unverified_cause_signals'] or 'none'}; observed in runs: pending.", "",
            "## Detection", "", f"An incident touching one of {raw['affected_services']} within {t['detection_deadline_seconds']} s of injection counts as detection.", "",
            "## RCA", "", f"Acceptable cause ids (equivalence class): {raw['ground_truth']['cause_equivalence_class']}; decoy causes: {raw['ground_truth']['decoy_causes'] or 'none'}.", "",
            "## Remediation", ""]
    acc = raw["accepted_remediation"]
    out.append(f"Expected outcome: `{acc['outcome']}`. Accepted actions: " + (", ".join(f"`{x['action_id']}({x['service']})`" for x in acc["actions"]) or "none") + ".")
    out += ["", "## Verification", "", "Verdicts are read from `GET /incidents/{id}/verification`; recovery time is the window end of the first `recovered` verdict.", "", "## Metrics", "",
            "Detection (MTTD, precision, recall, FP/h), diagnosis (top-1/top-3, evidence coverage, decoy rate), recovery, safety. AI metrics are out of scope.", "", "## Results", ""]
    if runs["total"] == 0:
        out.append(PENDING_SENTENCE)
    else:
        out += [f"Runs: {runs['experimental']} experimental, {runs['control']} control, {runs['aborted']} aborted, {runs['excluded_no_injection']} without injection.", "",
                "| Metric | Value |", "|---|---|"]
        rows = _rows(group)
        out += [f"| {k} | {v} |" for k, v in rows]
        if any(v == "pending" or v.startswith("pending") for _, v in rows):
            out += ["", f"Items marked pending: {PENDING_SENTENCE}"]
    out += ["", "## Analysis", "", PENDING_SENTENCE if runs["total"] == 0 else "Not written by the harness; the numbers above are the only claims it makes.", "",
            "## Failure Cases", "", f"See `{raw['design_doc']}`." + ("" if runs["total"] == 0 else f" Aborted runs: {runs['aborted']} (reasons are in the run records)."), "",
            "## Conclusion", "", PENDING_SENTENCE if runs["total"] == 0 else "No conclusion is drawn by the harness. N is stated in the table.", ""]
    return "\n".join(out)


def write_reports(records: list[RunRecord], scenarios: dict[str, Scenario], catalog: Catalog, base_dir: str | Path,
                  now: datetime | None = None) -> Path:
    now = now or datetime.now(UTC)
    summary = build_summary(records, scenarios, catalog, now)
    out = Path(base_dir) / now.strftime("%Y-%m-%d")
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    for sid, s in scenarios.items():
        md = scenario_markdown(s, summary["metrics"]["scenarios"][sid], summary["recoverability"][sid])
        (out / f"{sid.lower()}.md").write_text(md, encoding="utf-8")
    return out
